  var fallback = 'pt-BR';
  var current = fallback;

  var saved;
  try {
    saved = localStorage.getItem('iSalvei_lang');
  } catch (e) {}

  if (saved && locales[saved]) {
    current = saved;
  }

  function t(key, params) {
    var value = locales[current] && locales[current][key];
    if (value === undefined) {
      value = locales[fallback] && locales[fallback][key];
    }
    if (value === undefined) return key;
    if (params) {
      return value.replace(/\{\{(\w+)\}\}/g, function (_, param) {
        return params[param] !== undefined ? params[param] : '{{' + param + '}}';
      });
    }
    return value;
  }

  function getLocale() {
    return current;
  }

  function translateDOM() {
    var i;
    var el;
    var key;
    var value;

    var textEls = document.querySelectorAll('[data-i18n]');
    for (i = 0; i < textEls.length; i++) {
      el = textEls[i];
      key = el.getAttribute('data-i18n');
      value = t(key);
      if (value !== key) el.textContent = value;
    }

    var placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
    for (i = 0; i < placeholderEls.length; i++) {
      el = placeholderEls[i];
      key = el.getAttribute('data-i18n-placeholder');
      value = t(key);
      if (value !== key) el.placeholder = value;
    }

    var ariaEls = document.querySelectorAll('[data-i18n-aria-label]');
    for (i = 0; i < ariaEls.length; i++) {
      el = ariaEls[i];
      key = el.getAttribute('data-i18n-aria-label');
      value = t(key);
      if (value !== key) el.setAttribute('aria-label', value);
    }

    document.documentElement.lang = current;

    var metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.content = t('meta.description');

    var ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.content = t('meta.description');

    var titleTag = document.querySelector('title');
    if (titleTag) titleTag.textContent = t('meta.title');

    var appTitle = document.querySelector('meta[name="apple-mobile-web-app-title"]');
    if (appTitle) appTitle.content = 'iSalvei';
  }

  function setLocale(locale) {
    if (!locales[locale] || locale === current) return;
    current = locale;
    try {
      localStorage.setItem('iSalvei_lang', locale);
    } catch (e) {}
    translateDOM();
    document.dispatchEvent(new CustomEvent('localechange', { detail: { locale: locale } }));
  }

  translateDOM();

  window.i18n = {
    t: t,
    getLocale: getLocale,
    setLocale: setLocale
  };
